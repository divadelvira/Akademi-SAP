// Split a saved Claude artifact HTML into the Astro app's css / shell / js.
// Usage: npm run sync -- <path/to/artifact.html>
import { readFileSync, writeFileSync } from 'node:fs';
import assert from 'node:assert/strict';

const src = process.argv[2];
if (!src) { console.error('Usage: npm run sync -- <artifact.html>'); process.exit(1); }
const html = readFileSync(src, 'utf8');

const between = (open, close, from = 0) => {
  const a = html.indexOf(open, from);
  const b = close === '</script>' ? html.lastIndexOf(close) : html.indexOf(close, a);
  assert(a >= 0 && b > a, `missing ${open}…${close}`);
  return [html.slice(a + open.length, b).trim() + '\n', a];
};

const [css] = between('<style>', '</style>');
const body = html.indexOf('<body>');
const [shell] = between('<body>', '<script>', body);
const [js] = between('<script>', '</script>', body);

assert(css.includes(':root'), 'css looks wrong');
assert(shell.includes('id="view"'), 'shell looks wrong');
assert(js.includes('hashchange'), 'js looks wrong');

writeFileSync('src/styles/app.css', css);
writeFileSync('src/shell.html', shell);
writeFileSync('public/app.js', js);
console.log(`synced: css ${css.length}B, shell ${shell.length}B, js ${js.length}B`);

// Catalog for the server and admin page: roles and module ids, pulled from app.js literals.
const { runInNewContext } = await import('node:vm');
const lit = (name) => {
  const m = js.match(new RegExp(`^const ${name}=([\\s\\S]*?);$`, 'm'));
  assert(m, `catalog: const ${name} missing`);
  return runInNewContext(`(${m[1]})`);
};
const RGRP = lit('RGRP'), REL = lit('REL'), LEG_MAP = lit('LEG_MAP'), ORDER = lit('ORDER'), CATS = lit('CATS');
const ROLES = lit('ROLES').map(({ id, grp, t, d, w, g, p }) => ({ id, grp, t, d, w, g, p }));
const found = {};
for (const [, id, code, cat, title] of js.matchAll(/\{id:'([\w-]+)',code:'([^']+)',cat:'(\w+)',\s*title:'((?:[^'\\]|\\.)*)'/g)) found[id] = { id, code, cat, title };
for (const [id, code, cat, title] of Object.values(LEG_MAP)) found[id] = { id, code, cat, title };
const MODS = ORDER.map((id) => { assert(found[id], `catalog: module ${id} not found`); return found[id]; });
for (const r of ROLES) for (const id of [...r.w, ...r.g, ...r.p]) assert(found[id], `catalog: role ${r.id} uses unknown module ${id}`);
for (const hook of ['function renderModule(', 'function renderHome(', 'function renderRoles(', 'function renderRoleDetail(', 'function roleCard(', 'function modCard(', 'function route(', 'let S=', 'function save(', 'const MOD=']) {
  assert(js.includes(hook), `bridge hook "${hook}" missing, update public/access.js`);
}
const cats = CATS.map(({ id, t }) => ({ id, t }));
writeFileSync('functions/_lib/catalog.js',
  `// Generated by scripts/sync-artifact.mjs. Do not hand-edit.\n` +
  Object.entries({ RGRP, REL, ROLES, MODS, CATS: cats }).map(([k, v]) => `export const ${k} = ${JSON.stringify(v)};\n`).join(''));
console.log(`catalog: ${ROLES.length} roles, ${MODS.length} modules`);
